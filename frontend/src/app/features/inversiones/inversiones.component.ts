  private readonly gananciaMesActualPorMoneda = computed(() => {
    const { desde, hasta } = this.mesActualRango();
    return this.assets().filter(a => this.isActivo(a)).reduce((acc, a) => {
      const g = this.gananciaEnRango(a, desde, hasta);
      if (a.currency === 'ARS') acc.ars += g; else acc.usd += g;
      return acc;
    }, { ars: 0, usd: 0 });
  });

