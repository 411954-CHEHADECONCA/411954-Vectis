  /** Convierte y suma un desglose {ars, usd} a la moneda seleccionada. Si falta cotización, esa porción se omite. */
  private sumaConvertida(ars: number, usd: number): number {
    if (this.currencyService.selected() === 'ARS') {
      return ars + (this.currencyService.convert(usd, 'USD') ?? 0);
    }
    return (this.currencyService.convert(ars, 'ARS') ?? 0) + usd;
  }

  readonly capitalMostrado = computed(() => this.sumaConvertida(this.capitalARS(), this.capitalUSD()));

