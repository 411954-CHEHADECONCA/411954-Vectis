interface FCITramo {
  mov:       InvestmentMovement | null;
  saldo:     number;
  dias:      number;
  intereses: number;
  enCurso:   boolean;
  // Fecha de fin del tramo: la del siguiente movimiento, o hoy si es el tramo en curso.
  endDate:   string;
  // REVALUO que CIERRA este tramo: su monto es el interés realizado del período
  // (atribución hacia atrás) y ya está capitalizado en el saldo.
  closingRevaluo?: InvestmentMovement;
}

interface FCITramoCP {
  startDate:    string;
  endDate:      string;
  startPrice:   number;
  endPrice:     number;
  units:        number;
  dias:         number;
  ganancia:     number;   // units × (endPrice − startPrice)
  tna:          number;   // (ganancia/capitalInicio) × (365/dias) × 100
  tea:          number;   // ((1 + ganancia/capitalInicio)^(365/dias) − 1) × 100
  enCurso:      boolean;
  valuacionId?:  string;
  revaluoMovId?: string;
  // Tipo de operación que cierra el tramo (para mostrar en la tabla de tramos).
  endEvent?:     'SUSCRIPCION' | 'RESCATE' | 'REVALUO' | 'VALUACION';
  // True si el evento de cierre del tramo es una valuación generada al cerrar el mes del cashflow.
  endAutoGenerated?: boolean;
  tasaEfectiva: number;   // (ganancia / capitalInicio) × 100 — retorno del período sin anualizar
  tirAcumulada: number;   // TIR de todo el historial de movimientos hasta endDate, valuado con endPrice
}

function maturityAfterPurchaseValidator(g: AbstractControl): ValidationErrors | null {
  const purchase = g.get('purchaseDate')?.value as string | null;
  const maturity  = g.get('maturityDate')?.value  as string | null;
  if (!purchase || !maturity) return null;
  return maturity > purchase ? null : { maturityBeforePurchase: true };
}

