  /**
   * Bug 1: al crear un activo con seguimiento automático, siembra una valuación a la fecha de hoy
   * (o el último cierre disponible que devuelva la API) para que el activo muestre su valor actual
   * inmediatamente, sin esperar a la sincronización nocturna.
   */
  private _seedTodayValuation(asset: InvestmentResponse): void {
    if (!asset.autoTrack || !asset.externalId) return;
    const today = this.todayIso();
    if (asset.valuations?.some(v => v.valuationDate === today)) return;

    // Cada fuente devuelve el precio y la FECHA a la que corresponde: FCI usa el snapshot del día;
    // PPI devuelve el último cierre real (para instrumentos ilíquidos puede ser de semanas atrás),
    // por lo que la valuación se persiste en esa fecha verídica, no en "hoy".
    const seed$ = asset.type === 'FCI_CUOTAPARTES'
      ? this.investmentService.getFciVcp(asset.externalId, today)
          .pipe(map(r => r?.vcp != null ? { price: r.vcp, date: today } : null))
      : this.investmentService.getInstrumentPrice(asset.externalId, asset.type, today)
          .pipe(map(r => r?.pricePerUnit != null ? { price: r.pricePerUnit, date: r.fecha ?? today } : null));

    seed$.pipe(
      switchMap(seed => {
        if (!seed) return of(null);
        // No re-persistir si ya existe una valuación en esa fecha (p. ej. el backfill ya la trajo):
        // addValuation rechaza fechas duplicadas con 409.
        if (asset.valuations?.some(v => v.valuationDate === seed.date)) return of(null);
        return this.investmentService.addValuation(asset.id, { valuationDate: seed.date, pricePerUnit: seed.price });
      }),
      takeUntilDestroyed(this.destroyRef),
    ).subscribe(updated => {
      if (updated) {
        this.assets.update(list => list.map(a => a.id === updated.id ? updated : a));
      }
    });
  }

  // ── Triángulo monto/unidades/precio ──────────────────────────────────────
  onAmountInput(form: FormGroup): void {
    const amount = form.get('amount')?.value as number | null;
    const price  = form.get('pricePerUnit')?.value as number | null;
    const units  = form.get('units')?.value as number | null;
    if (amount != null && price != null && price !== 0) {
      form.get('units')?.setValue(parseFloat((amount / price).toFixed(6)), { emitEvent: false });
    } else if (amount != null && units != null && units !== 0) {
      form.get('pricePerUnit')?.setValue(parseFloat((amount / units).toFixed(6)), { emitEvent: false });
    }
  }

  onUnitsInput(form: FormGroup): void {
    const units  = form.get('units')?.value as number | null;
    const price  = form.get('pricePerUnit')?.value as number | null;
    if (units != null && price != null && price !== 0) {
      form.get('amount')?.setValue(parseFloat((units * price).toFixed(2)), { emitEvent: false });
    }
  }

  onPricePerUnitInput(form: FormGroup): void {
    const price  = form.get('pricePerUnit')?.value as number | null;
    const amount = form.get('amount')?.value as number | null;
    const units  = form.get('units')?.value as number | null;
    if (price != null && price !== 0) {
      if (amount != null) {
        form.get('units')?.setValue(parseFloat((amount / price).toFixed(6)), { emitEvent: false });
      } else if (units != null) {
        form.get('amount')?.setValue(parseFloat((units * price).toFixed(2)), { emitEvent: false });
      }
    }
  }

